package piscine

func ConcatParams(args []string) string {
	// 1. Создаем переменную для хранения итоговой строки
	var result string

	// 2. Бежим циклом по всему слайсу аргументов
	for i := 0; i < len(args); i++ {
		// Если это первый элемент, просто присваиваем его (или добавляем к пустой строке)
		if i == 0 {
			result += args[i]
		} else {
			// Для всех остальных сначала добавляем перенос строки, а потом само слово
			result += "\n" + args[i]
		}
	}

	// 3. Возвращаем склеенную строку
	return result
}
