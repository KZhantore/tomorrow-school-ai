package piscine

import "github.com/01-edu/z01"

func PrintNbr(n int) {
	if n == 0 {
		z01.PrintRune('0')
		return
	}

	// Выносим логику в отдельную рекурсивную функцию,
	// которая умеет правильно работать с отрицательными числами
	printRecursive(n)
}

func printRecursive(n int) {
	if n == 0 {
		return
	}

	// Шаг рекурсии: уходим глубже, отсекая последнюю цифру
	printRecursive(n / 10)

	// Вычисляем остаток
	mod := n % 10

	// Если число было отрицательным, остаток тоже будет отрицательным (например, -8)
	// Нам нужно инвертировать его, чтобы прибавить к '0'
	if mod < 0 {
		// Если это самая первая цифра отрицательного числа, перед ней нужно напечатать минус
		// Мы узнаем, что это первая цифра, если n/10 вернул 0 (то есть глубже рекурсия не пошла)
		if n/10 == 0 {
			z01.PrintRune('-')
		}
		mod = -mod
	}

	z01.PrintRune('0' + rune(mod))
}
