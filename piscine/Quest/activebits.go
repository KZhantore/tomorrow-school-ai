package piscine

func ActiveBits(n int) int {
	count := 0
	// Обрабатываем случай, если число отрицательное,
	// переводя его в положительное (хотя для побитовых операций в тестах обычно дают >= 0)
	if n < 0 {
		n = -n
	}
	// Пока в числе остались биты
	for n > 0 {
		// n & 1 возвращает 1, если последний бит равен единице, и 0, если нулю
		count += n & 1
		// Сдвигаем число вправо на 1 бит (делим на 2)
		n = n >> 1
	}
	return count
}
