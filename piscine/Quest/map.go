package piscine

// Map применяет функцию f к каждому элементу среза a и возвращает срез результатов.
func Map(f func(int) bool, a []int) []bool {
	// Создаем новый срез нужной длины для хранения результатов true/false
	result := make([]bool, len(a))

	// Проходим циклом по всем элементам исходного среза
	for i, v := range a {
		// Применяем функцию f к значению v и записываем результат в i-ю позицию
		result[i] = f(v)
	}

	// Возвращаем итоговый срез
	return result
}
