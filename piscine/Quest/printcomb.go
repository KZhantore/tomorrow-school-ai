package piscine

import "github.com/01-edu/z01"

func PrintComb() {
	// Первый цикл для первой цифры (i). Она может идти максимум до '7' (так как последняя комбинация — 789)
	for i := '0'; i <= '7'; i++ {
		// Вторая цифра (j) всегда строго больше первой
		for j := i + 1; j <= '8'; j++ {
			// Третья цифра (k) всегда строго больше второй
			for k := j + 1; k <= '9'; k++ {

				// Выводим три цифры комбинации последовательно
				z01.PrintRune(i)
				z01.PrintRune(j)
				z01.PrintRune(k)

				// Выводим запятую и пробел для всех комбинаций, кроме самой последней (789)
				if !(i == '7' && j == '8' && k == '9') {
					z01.PrintRune(',')
					z01.PrintRune(' ')
				}
			}
		}
	}
	// В самом конце выводим символ новой строки, чтобы вывод был красивым в терминале
	z01.PrintRune('\n')
}
