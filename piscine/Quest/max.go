package piscine

func Max(a []int) int {
	// Если слайс пустой, возвращаем 0 согласно условию
	if len(a) == 0 {
		return 0
	}
	// Инициализируем переменную max первым элементом слайса
	max := a[0]
	// Проходим по всем остальным элементам слайса
	for i := 1; i < len(a); i++ {
		// Если текущий элемент больше, чем сохраненный max, обновляем его
		if a[i] > max {
			max = a[i]
		}
	}
	return max
}
